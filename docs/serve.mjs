/**
 * Static server for the documentation site — the second half of the deploy.
 *
 *   node docs/serve.mjs          # http://localhost:8099
 *   PORT=3000 node docs/serve.mjs
 *
 * Deliberately dependency-free: `node:http` and `node:fs` only. Adding `serve` or `express` for
 * forty lines of file-reading would cost this repo its "no native deps, nothing to compile, clone
 * and run" property, which is one of the few things here that is genuinely hard to get back.
 *
 * It also fixes the reason the docs are not simply dropped into `public/`: Next serves files from
 * `public/` by exact path and makes no promise about mapping a directory request to `index.html`,
 * so `/docs/` could 404 while `/docs/index.html` worked. Here that mapping is explicit.
 */
import { createReadStream, existsSync, statSync } from 'node:fs';
import { createServer } from 'node:http';
import { extname, join, normalize, resolve, sep } from 'node:path';

const ROOT = resolve(import.meta.dirname, 'site');
const PORT = Number(process.env.PORT ?? 8099);

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.mjs': 'text/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.webp': 'image/webp',
  '.ico': 'image/x-icon',
  '.woff': 'font/woff',
  '.woff2': 'font/woff2',
  '.txt': 'text/plain; charset=utf-8',
  '.md': 'text/markdown; charset=utf-8',
};

/**
 * Resolve a URL path to a file inside ROOT, or null.
 *
 * The containment check is the point: `normalize` collapses `..` segments, and we then require the
 * result to still sit under ROOT. Without that, `GET /../../.pyai-key.json` would serve the key
 * file this repo spent real effort keeping out of git.
 */
function resolveFile(urlPath) {
  let decoded;
  try {
    decoded = decodeURIComponent(urlPath.split('?')[0]);
  } catch {
    return null; // malformed percent-encoding
  }
  if (decoded.includes('\0')) return null;

  const candidate = resolve(join(ROOT, normalize(decoded)));
  if (candidate !== ROOT && !candidate.startsWith(ROOT + sep)) return null;

  if (existsSync(candidate) && statSync(candidate).isDirectory()) {
    const index = join(candidate, 'index.html');
    return existsSync(index) ? index : null;
  }
  if (existsSync(candidate)) return candidate;

  // Allow /09-run-and-verify to reach 09-run-and-verify.html.
  const withHtml = `${candidate}.html`;
  return existsSync(withHtml) ? withHtml : null;
}

const server = createServer((req, res) => {
  if (req.method !== 'GET' && req.method !== 'HEAD') {
    res.writeHead(405, { 'Content-Type': 'text/plain', Allow: 'GET, HEAD' });
    res.end('Method not allowed\n');
    return;
  }

  const file = resolveFile(req.url ?? '/');
  if (!file) {
    res.writeHead(404, { 'Content-Type': 'text/html; charset=utf-8' });
    res.end('<h1>404</h1><p>No such page. <a href="/">Documentation index</a>.</p>\n');
    return;
  }

  const type = TYPES[extname(file).toLowerCase()] ?? 'application/octet-stream';
  const { size, mtime } = statSync(file);
  res.writeHead(200, {
    'Content-Type': type,
    'Content-Length': size,
    'Last-Modified': mtime.toUTCString(),
    // The pages are regenerated by docs/site/build.py and redeployed; a short cache keeps an
    // updated deploy from being invisible behind a stale copy.
    'Cache-Control': 'public, max-age=300',
    'X-Content-Type-Options': 'nosniff',
  });
  if (req.method === 'HEAD') {
    res.end();
    return;
  }
  createReadStream(file).pipe(res);
});

server.listen(PORT, () => {
  console.log(`OpenGong Lite docs on http://localhost:${PORT} (serving ${ROOT})`);
});
